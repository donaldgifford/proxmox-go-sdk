// coverageBaseline and coverageRoutes are a fixture pair the real mock cannot
// stand in for: measuring mockpve's whole route table against a two-endpoint
// baseline would report every route as fabricated.
const coverageBaseline = `[
  {"method":"GET","path":"/version"},
  {"method":"GET","path":"/nodes/{node}/qemu"},
  {"method":"POST","path":"/nodes/{node}/qemu"}
]`

const coverageAnnotations = `baseline:
  pve_version: "9.2.4"
  source: "fixture"
  captured: "2026-01-01"
`

var coverageRoutes = []string{
	"GET /api2/json/version",
	"GET /api2/json/nodes/{node}/qemu",
}

// coverageOpts is the happy-path coverage invocation, writing into a temp dir.
func coverageOpts(t *testing.T) *options {
	t.Helper()
	return &options{
		coverage:    true,
		baseline:    writeTemp(t, "baseline.json", coverageBaseline),
		annotations: writeTemp(t, "annotations.yaml", coverageAnnotations),
		out:         filepath.Join(t.TempDir(), "COVERAGE.md"),
		routes:      coverageRoutes,
	}
}

func TestRunCoverageWritesThenVerifies(t *testing.T) {
	t.Parallel()
	opts := coverageOpts(t)

	report, fail, err := run(opts)
	if err != nil {
		t.Fatalf("run(coverage): %v", err)
	}
	if fail {
		t.Errorf("run(coverage) fail = true, want false; output=%q", report)
	}
	if !strings.Contains(report, "2 of 3 endpoint(s) covered (66.7%)") {
		t.Errorf("write output = %q, want the covered summary", report)
	}
	written, err := os.ReadFile(opts.out)
	if err != nil {
		t.Fatalf("read written report: %v", err)
	}
	if !bytes.HasPrefix(written, []byte("<!-- Generated by")) {
		t.Errorf("written report does not start with the generated marker: %.40q", written)
	}

	// -check against what was just written: current.
	opts.check = true
	report, fail, err = run(opts)
	if err != nil {
		t.Fatalf("run(coverage -check): %v", err)
	}
	if fail {
		t.Errorf("run(coverage -check) fail = true on a fresh report; output=%q", report)
	}
	if !strings.Contains(report, "is current") {
		t.Errorf("check output = %q, want 'is current'", report)
	}
}

// A hand-edited report fails the drift check — the doc is machine-owned.
func TestRunCoverageDetectsDrift(t *testing.T) {
	t.Parallel()
	opts := coverageOpts(t)
	if _, _, err := run(opts); err != nil {
		t.Fatalf("run(coverage): %v", err)
	}
	if err := os.WriteFile(opts.out, []byte("# hand-written\n"), 0o600); err != nil {
		t.Fatalf("tamper: %v", err)
	}

	opts.check = true
	report, fail, err := run(opts)
	if err != nil {
		t.Fatalf("run(coverage -check): %v", err)
	}
	if !fail {
		t.Fatal("run(coverage -check) fail = false on a tampered report, want true")
	}
	if !strings.Contains(report, "is stale") || !strings.Contains(report, "just coverage") {
		t.Errorf("drift output = %q, want the stale-report message", report)
	}
}

// The fabrication guard fails the run and, crucially, fails it BEFORE writing:
// a report naming endpoints that do not exist must never reach disk.
func TestRunCoverageGuardBlocksTheWrite(t *testing.T) {
	t.Parallel()
	opts := coverageOpts(t)
	opts.routes = append(opts.routes, "GET /api2/json/cluster/sdn/fabrics")

	report, fail, err := run(opts)
	if err != nil {
		t.Fatalf("run(coverage): %v", err)
	}
	if !fail {
		t.Fatal("run(coverage) fail = false with a fabricated route, want true")
	}
	if !strings.Contains(report, "/cluster/sdn/fabrics") {
		t.Errorf("guard output = %q, want the offending route named", report)
	}
	if _, err := os.Stat(opts.out); !os.IsNotExist(err) {
		t.Errorf("the report was written despite the guard failing (stat err = %v)", err)
	}
}

