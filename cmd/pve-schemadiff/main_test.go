// Flag combinations that would silently check nothing are rejected, so a typo in
// a CI invocation fails loudly instead of passing.
func TestOptionsValidate(t *testing.T) {
	t.Parallel()
	tests := []struct {
		name string
		opts options
		want string
	}{
		{"no baseline", options{apidoc: "a.js"}, "-baseline is required"},
		{"no apidoc", options{baseline: "b.json"}, "-apidoc is required"},
		{
			"coverage flags in schema-diff mode",
			options{apidoc: "a.js", baseline: "b.json", out: "c.md"},
			"apply to -coverage only",
		},
		{
			"coverage without annotations",
			options{coverage: true, baseline: "b.json"},
			"-annotations is required",
		},
		{
			"update in coverage mode",
			options{coverage: true, baseline: "b.json", annotations: "a.yaml", update: true},
			"-update applies to schema-diff mode only",
		},
		{
			"check without out",
			options{coverage: true, baseline: "b.json", annotations: "a.yaml", check: true},
			"-check needs -out",
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			err := tc.opts.validate()
			if err == nil {
				t.Fatalf("validate() = nil, want an error containing %q", tc.want)
			}
			if !strings.Contains(err.Error(), tc.want) {
				t.Errorf("validate() = %v, want an error containing %q", err, tc.want)
			}
		})
	}

	valid := []options{
		{apidoc: "a.js", baseline: "b.json"},
		{apidoc: "a.js", baseline: "b.json", update: true},
		{coverage: true, baseline: "b.json", annotations: "a.yaml"},
		{coverage: true, baseline: "b.json", annotations: "a.yaml", out: "c.md", check: true},
	}
	for i, opts := range valid {
		if err := opts.validate(); err != nil {
			t.Errorf("valid[%d].validate() = %v, want nil", i, err)
		}
	}
}
