package coverage

import (
	"fmt"
	"strings"
)

// GeneratedMarker opens every rendered report. The drift check compares bytes,
// so the file is machine-owned; the marker says so to anyone who opens it.
const GeneratedMarker = "<!-- Generated by `just coverage`. DO NOT EDIT — regenerate instead. -->"

// Markdown renders the report exactly as docs/COVERAGE.md is committed.
//
// The output is byte-stable for a given input: every section and row comes from
// a sorted slice, never a map walk. That is a hard requirement, not tidiness —
// the drift check diffs a regeneration against the committed file, so any
// nondeterminism would fail CI at random.
//
// Table cells are deliberately unpadded. A padded table reflows every row when
// one long path is added, which buries the real change in the diff.
func (r *Report) Markdown() string {
	var b strings.Builder
	r.writeHeader(&b)
	r.writeSummary(&b)
	r.writeSideChannel(&b)
	r.writeAllowlisted(&b)
	r.writeServices(&b)
	return b.String()
}

// writeHeader states what was measured and, just as importantly, what the
// percentage does not mean.
func (r *Report) writeHeader(b *strings.Builder) {
	fmt.Fprintf(b, "%s\n\n# Proxmox VE API coverage\n\n", GeneratedMarker)
	fmt.Fprintf(b, "The SDK reaches **%d of %d endpoints (%s)** in the Proxmox VE %s REST API.\n\n",
		r.Totals.Covered, r.Totals.Total, r.Totals.Percent(), r.Baseline.PVEVersion)
	b.WriteString("The percentage is **not a target**. It is measured against the *entire* REST\n" +
		"API, including surfaces no SDK consumer has asked for; driving it up for its own\n" +
		"sake would mean shipping untested breadth. Read it as a map of what exists, and\n" +
		"use the per-service tables to find whether a specific endpoint is reachable.\n\n")
	b.WriteString("| | |\n|---|---|\n")
	fmt.Fprintf(b, "| Measured against | Proxmox VE %s (`%s`, captured %s) |\n",
		r.Baseline.PVEVersion, r.Baseline.Source, r.Baseline.Captured)
	fmt.Fprintf(b, "| Denominator | %d endpoints in `cmd/pve-schemadiff/testdata/baseline.json` |\n",
		r.Totals.Total)
	fmt.Fprintf(b, "| Numerator | %d distinct `mockpve` routes (%d matched a real endpoint) |\n",
		r.RouteCount, r.Totals.Covered)
	b.WriteString("| Regenerate | `just coverage` |\n\n")
	b.WriteString("A **covered** endpoint has a `mockpve` route, which by this repo's discipline of\n" +
		"testing every op against `mockpve` means an SDK method drives it. A **stub** is a\n" +
		"deliberate `pverr.ErrUnsupported`, with its reason. **Out of scope** is a decision,\n" +
		"with the document that made it. Everything else is a **gap** — including families\n" +
		"nobody has triaged yet.\n\n")
}

// writeSummary renders the per-service totals table.
func (r *Report) writeSummary(b *strings.Builder) {
	b.WriteString("## Summary\n\n| Service | Covered | Stub | Out of scope | Gap | Total | Share |\n")
	b.WriteString("|---|--:|--:|--:|--:|--:|--:|\n")
	for _, s := range r.Services {
		fmt.Fprintf(b, "| %s | %d | %d | %d | %d | %d | %s |\n",
			s.Name, s.Covered, s.Stub, s.OutOfScope, s.Gap, s.Total, s.Percent())
	}
	fmt.Fprintf(b, "| **total** | **%d** | **%d** | **%d** | **%d** | **%d** | **%s** |\n\n",
		r.Totals.Covered, r.Totals.Stub, r.Totals.OutOfScope, r.Totals.Gap,
		r.Totals.Total, r.Totals.Percent())
}

// writeSideChannel lists the capabilities that exist outside REST entirely, so
// they are not silently absent from a report keyed by endpoint.
func (r *Report) writeSideChannel(b *strings.Builder) {
	if len(r.SideChannel) == 0 {
		return
	}
	b.WriteString("## Covered outside REST\n\n" +
		"PVE serves no endpoint for these; the SDK covers them over the `proxmox/ssh`\n" +
		"side channel, so they appear in no table below.\n\n")
	for _, s := range r.SideChannel {
		fmt.Fprintf(b, "- %s\n", s)
	}
	b.WriteString("\n")
}

// writeAllowlisted surfaces the fabrication guard's exemptions. Rendering them
// in the committed report is the point: an exemption is a claim that the
// baseline is wrong, and it should be uncomfortable to leave in place.
func (r *Report) writeAllowlisted(b *strings.Builder) {
	if len(r.Findings.AllowedRoutes) == 0 {
		return
	}
	b.WriteString("## Allowlisted unmatched routes\n\n" +
		"`mockpve` serves these, but the baseline holds no such endpoint. Each is an\n" +
		"exemption from the fabrication guard, and each is debt: either the baseline is\n" +
		"stale or the route is wrong.\n\n| Route | Reason |\n|---|---|\n")
	for _, a := range r.Findings.AllowedRoutes {
		fmt.Fprintf(b, "| `%s` | %s |\n", a.Route, cell(a.Reason))
	}
	b.WriteString("\n")
}

// writeServices renders one table per service, every endpoint listed.
func (r *Report) writeServices(b *strings.Builder) {
	b.WriteString("## Per-service detail\n")
	for _, s := range r.Services {
		fmt.Fprintf(b, "\n### %s\n\n%d of %d covered (%s)\n\n| Method | Path | State | Note |\n|---|---|---|---|\n",
			s.Name, s.Covered, s.Total, s.Percent())
		for _, row := range s.Rows {
			fmt.Fprintf(b, "| %s | `%s` | %s | %s |\n",
				row.Key.Method, row.Key.Path, row.State, cell(row.Note))
		}
	}
}

// cell escapes the one character that would break a table row. Notes are
// hand-written in the annotations file, so a stray pipe is a real possibility.
func cell(s string) string {
	return strings.ReplaceAll(s, "|", `\|`)
}
